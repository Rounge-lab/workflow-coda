"""Pins for the tutorial examples: what the documentation ships is
what the framework builds.

The hello-report files under ``docs/examples/hello-report`` are
included into the tutorial page verbatim, and these pins drive the
real CLI against them — the tutorial cannot drift from the
framework without this suite going red.
"""

from pathlib import Path

import pytest

from workflow_coda.cli import main

HELLO = Path(__file__).resolve().parents[1] / "docs" / "examples" / "hello-report"
"""The shipped tutorial files — the docs include exactly what this
suite builds."""


def test_the_hello_report_builds_as_documented(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # The real CLI over the shipped files, through the real plugin
    # discovery: the report the tutorial describes is the report the
    # framework builds.
    output = tmp_path / "report.html"
    code = main(
        [
            "build",
            str(HELLO / "manifest.json"),
            str(HELLO / "layout.yaml"),
            "-o",
            str(output),
        ]
    )
    assert code == 0
    out, err = capsys.readouterr()
    assert out == ""
    assert err == ""
    page = output.read_text(encoding="utf-8")

    # The page the tutorial promises: the title in the header bar,
    # one KPI card reading the declared artifact, no tab bar — a
    # single tab is not yet navigation.
    assert page.lstrip().startswith("<!doctype html>")
    assert "<title>Run summary</title>" in page
    assert 'data-component="core.kpi"' in page
    assert "Mean depth" in page
    assert "42.7" in page
    assert 'role="tablist"' not in page

    # The placed ledger, honest to the final layout: theme and logo
    # declared, favicon not — exactly one note, and the two the
    # tutorial's last beat declared are gone.
    assert (
        '<span class="coda-badge coda-badge--favicon_omitted">'
        "favicon_omitted</span>" in page
    )
    assert "coda-badge--default_theme" not in page
    assert "coda-badge--logo_omitted" not in page

    # The declared look: the midnight theme on the page, its accent
    # as the bar, and the named icon inlined as svg in the brand —
    # nothing else in this report can emit one.
    assert "--coda-background: #10141a;" in page
    assert "--coda-header-background: #acc6f5;" in page
    assert "<svg" in page

    # Provenance: the manifest's own record of itself.
    assert "Produced by my-pipeline 1.0.0" in page
    assert "1 of 1 artifacts completed" in page
    assert "This report was generated by workflow-coda" in page
