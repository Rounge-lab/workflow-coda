@pytest.fixture
def waterfall_module(monkeypatch: pytest.MonkeyPatch) -> ModuleType:
    """The shipped plugin module, imported straight from the example
    tree.  The dev environment does not entry-point-install the
    example plugin, so the pins assemble the registry explicitly —
    the reader's ``pip install`` makes discovery automatic."""
    monkeypatch.syspath_prepend(str(WATERFALL))
    import waterfall_reports.plugin as module  # type: ignore[import-not-found]

    # The ignored import leaves the name Any; the assert narrows it to
    # the declared type — and states a true runtime fact: an imported
    # module is always a ModuleType instance.
    assert isinstance(module, ModuleType)
    return module


def render_waterfall(
    module: ModuleType, store: ArtifactStore, parameters: dict[str, object]
) -> RenderedComponent:
    """One render call against a real context.  Attribute access on a
    ModuleType is Any (typeshed's permissive ``__getattr__``), so the
    isinstance on the outcome is the contract check that keeps the
    declared return honest."""
    outcome = module.render_waterfall(
        RenderContext(store=store),
        PlacementInfo(title="Where the bases went"),
        parameters,
    )
    assert isinstance(outcome, RenderedComponent)
    return outcome


def store_with_steps(tmp_path: Path, steps: str | None) -> ArtifactStore:
    """A store declaring the tutorial's two artifacts; *steps*, when
    given, is written as the waterfall artifact's file."""
    if steps is not None:
        (tmp_path / "steps.json").write_text(steps, encoding="utf-8")
    manifest = ReportManifest.model_validate(
        make_manifest_payload(
            artifacts=[
                make_artifact_payload(),
                make_artifact_payload(
                    id="composition",
                    type="org.example.waterfall",
                    path="steps.json",
                    format="json",
                ),
            ]
        )
    )
    return ArtifactStore(manifest, tmp_path)


def test_the_waterfall_plugin_assembles(waterfall_module: ModuleType) -> None:
    plugin = waterfall_module.get_plugin()
    assert plugin.metadata.id == "waterfall"
    assert plugin.metadata.supported_schema_versions == frozenset(
        {MANIFEST_SCHEMA_VERSION}
    )
    (component,) = plugin.components
    assert component.id == "waterfall.plot"
    assert component.render is waterfall_module.render_waterfall


def test_waterfall_renders_its_figure_from_the_artifact(
    waterfall_module: ModuleType, tmp_path: Path
) -> None:
    outcome = render_waterfall(
        waterfall_module,
        store_with_steps(tmp_path, STEPS),
        {"artifact": "org.example.waterfall", "unit": "Gbp"},
    )
    assert outcome.status is ComponentStatus.OK
    assert outcome.html is not None
    assert "coda-figure" in outcome.html
    # The framework's figure channel: bare div, no plotly.js bundle,
    # the accessibility label from the tutorial's one line.
    assert "Plotly.newPlot" in outcome.html
    assert 'aria-label="Waterfall chart: Where the bases went across 2 steps"' in (
        outcome.html
    )
    assert "Gbp" in outcome.html  # the unit rides the y-axis title


def test_waterfall_missing_data_is_a_notice_not_a_failure(
    waterfall_module: ModuleType, tmp_path: Path
) -> None:
    # The honest-data law: the artifact type is not declared, so the
    # store's teaching rides an unavailable outcome — the reader sees
    # a quiet notice, and the declared vocabulary comes with it.
    store = ArtifactStore(
        ReportManifest.model_validate(make_manifest_payload()), tmp_path
    )
    outcome = render_waterfall(
        waterfall_module, store, {"artifact": "org.example.waterfall"}
    )
    assert outcome.status is ComponentStatus.UNAVAILABLE
    assert outcome.message is not None
    assert "manifest declares no artifact of type 'org.example.waterfall'" in (
        outcome.message
    )


def test_malformed_steps_teach_the_content_contract(
    waterfall_module: ModuleType, tmp_path: Path
) -> None:
    # A present, complete artifact whose content breaks the documented
    # shape is a raised teaching error — the builder's failure card
    # will quote it.  The bool trap rides along: JSON booleans are not
    # numbers, and the validator says so.
    store = store_with_steps(tmp_path, '{"steps": [{"label": "A", "value": true}]}')
    with pytest.raises(ValueError, match="step 0 'value' must be a number"):
        render_waterfall(waterfall_module, store, {"artifact": "org.example.waterfall"})


def test_waterfall_without_plotly_teaches_the_install(
    waterfall_module: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    # The lazy-import contract: no plotly, no crash — one instruction.
    # The simulation must be faithful to a plotly-less machine: a
    # None entry under 'plotly' alone does not do it once earlier
    # tests have imported plotly — the from-import finds the cached
    # submodules and skips the halt, and the failure surfaces later,
    # inside the Figure constructor, as an uncaught
    # ModuleNotFoundError.  Purge every cached plotly entry first
    # (monkeypatch restores them on teardown), then halt the
    # top-level name — a fresh interpreter without plotly.
    for name in [n for n in sys.modules if n == "plotly" or n.startswith("plotly.")]:
        monkeypatch.delitem(sys.modules, name)
    monkeypatch.setitem(sys.modules, "plotly", None)
    with pytest.raises(RenderError, match="install plotly"):
        render_waterfall(
            waterfall_module,
            store_with_steps(tmp_path, STEPS),
            {"artifact": "org.example.waterfall"},
        )


def test_the_waterfall_report_builds_as_documented(
    tmp_path: Path, waterfall_module: ModuleType
) -> None:
    # The reader's working directory, assembled from the shipped
    # files: the first tutorial's artifacts and theme, the second's
    # extended manifest and layout.  The registry is core plus the
    # tutorial's plugin — exactly what the reader's install gives the
    # CLI for free.
    for name in ("depth.json", "theme.yaml"):
        shutil.copy(HELLO / name, tmp_path)
    for name in ("steps.json", "manifest.json", "layout.yaml"):
        shutil.copy(WATERFALL / name, tmp_path)
    document = build_report(
        tmp_path / "layout.yaml",
        ArtifactStore.from_manifest_file(tmp_path / "manifest.json"),
        PluginRegistry((get_core_plugin(), waterfall_module.get_plugin())),
    )
    page = render_report(document)

    # The continuity beat: the second tab brings the tab bar, and both
    # panels pair with their buttons.
    assert '<nav class="coda-tabs" role="tablist"' in page
    assert 'id="tabbtn-1-headlines"' in page
    assert 'id="tabbtn-2-composition"' in page
    assert 'id="2-composition"' in page
    # Both components rendered: the framework's KPI and the reader's
    # own waterfall, through the figure channel.
    assert 'data-component="core.kpi"' in page
    assert 'data-component="waterfall.plot"' in page
    assert "coda-figure" in page
    assert "Plotly.newPlot" in page
    assert "42.7" in page
    # Self-containment holds with figures, and the census is
    # accounted: Plotly.js (the figure), the tab script (two tabs),
    # and the core KPI's own enhancement script — the component page
    # chrome channel, which the chrome-less waterfall component does
    # not add to.
    assert page.count("<script>") == 4
    # The look carried over: the tutorial's theme and its accent bar.
    assert "--coda-header-background: #acc6f5;" in page
    assert 'aria-label="Waterfall chart: Where the bases went across 4 steps"' in page
    # The ledger stays honest: theme and logo declared, favicon not.
    assert "coda-badge--favicon_omitted" in page
    assert "2 of 2 artifacts completed" in page
